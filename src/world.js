const ENTITY_CHARS = 'PBcbhDSKH';

export class World {
  constructor(rooms = ROOMS) {
    this.rooms = rooms;
    let maxCx = 0, maxCy = 0;
    for (const r of rooms) {
      maxCx = Math.max(maxCx, r.cx + r.w);
      maxCy = Math.max(maxCy, r.cy + r.h);
    }
    this.cellsW = maxCx;
    this.cellsH = maxCy;
    this.tw = maxCx * CW;
    this.th = maxCy * CH;
    this.grid = new Array(this.tw * this.th).fill('#');
    this.roomGrid = new Array(this.tw * this.th).fill(null);
    this.spawns = [];

    for (const r of rooms) {
      const ox = r.cx * CW, oy = r.cy * CH;
      r.px = ox * T; r.py = oy * T;
      r.pw = r.w * CW * T; r.ph = r.h * CH * T;
      for (let y = 0; y < r.h * CH; y++) {
        const row = r.map[y] || '';
        for (let x = 0; x < r.w * CW; x++) {
          let ch = row[x] || '#';
          const tx = ox + x, ty = oy + y;
          if (ENTITY_CHARS.includes(ch)) {
            this.spawns.push({
              type: ch, room: r.id, tx, ty,
              id: `${ch}@${tx},${ty}`,
              x: tx * T + T / 2, y: (ty + 1) * T,
            });
            ch = '.';
          }
          this.grid[ty * this.tw + tx] = ch;
          this.roomGrid[ty * this.tw + tx] = r;
        }
      }
    }
    this.roomById = Object.fromEntries(rooms.map(r => [r.id, r]));
  }

  tile(tx, ty) {
    if (tx < 0 || ty < 0 || tx >= this.tw || ty >= this.th) return '#';
    return this.grid[ty * this.tw + tx];
  }
  setTile(tx, ty, ch) { this.grid[ty * this.tw + tx] = ch; }
  solid(tx, ty) { const c = this.tile(tx, ty); return c === '#' || c === 'X'; }
  oneWay(tx, ty) { return this.tile(tx, ty) === '='; }
  spike(tx, ty) { return this.tile(tx, ty) === '^'; }

  roomAtPx(px, py) {
    const tx = Math.floor(px / T), ty = Math.floor(py / T);
    if (tx < 0 || ty < 0 || tx >= this.tw || ty >= this.th) return null;
    return this.roomGrid[ty * this.tw + tx];
  }

  // 打碎与 (tx,ty) 相连的整块裂墙，返回碎掉的格子
  breakWall(tx, ty) {
    const out = [];
    const stack = [[tx, ty]];
    while (stack.length) {
      const [x, y] = stack.pop();
      if (this.tile(x, y) !== 'X') continue;
      this.setTile(x, y, '.');
      out.push([x, y]);
      stack.push([x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]);
    }
    return out;
  }
}
